"""Writes the warehouse goods tables in scripts/company_state_base.gd from data/catalog.json
(run from the project root after tools/catalog_gen.py, whenever expeditions open).

Goods = every material a live expedition yields (sites in scripts/sites.gd), the two
treasures, and everything craftable that isn't worn as gear: intermediates, potions, food.
"""
import json, re

cat = json.load(open("data/catalog.json"))
sites_src = open("scripts/sites.gd").read()
live_sites = set(re.findall(r'"id": "(\w+)", "name"', sites_src))
M, I = cat["materials"], cat["items"]

GROUP_ORDER = ["timber", "sap", "ore", "metal", "gem", "herb", "fish", "meat", "hide", "hunt", "fibre", "crop", "treasure"]
mats = [k for k, m in M.items() if set(m["sources"]) & live_sites or k in ("relic", "sovereign")]
mats.sort(key=lambda k: (GROUP_ORDER.index(M[k]["group"]), M[k]["tier"], M[k]["value"]))
crafted = [k for k, v in I.items() if v["category"] == "material"]
crafted.sort(key=lambda k: (I[k]["tier"], I[k]["value"]))
potions = sorted([k for k, v in I.items() if v["category"] == "potion"], key=lambda k: (I[k]["tier"], I[k]["value"]))
food = sorted([k for k, v in I.items() if v["category"] == "food"], key=lambda k: (I[k]["tier"], I[k]["value"]))
order = mats + crafted + potions + food

def name(k):
    return (M.get(k) or I.get(k))["name"]
def value(k):
    return (M.get(k) or I.get(k))["value"]
def desc(k):
    if k in M:
        return M[k]["note"]
    d = I[k]
    return d.get("note", "")

def gd_list(items, per=8):
    rows = []
    for i in range(0, len(items), per):
        rows.append("\t" + ", ".join(items[i:i + per]) + ",")
    return "\n".join(rows).rstrip(",")

block = "## Goods the warehouse holds and the markets trade: every material a live expedition yields,\n"
block += "## the treasures, and what anyone can craft that isn't worn: ingots, linen, potions and food.\n"
block += "## Generated by tools/goods_gen.py from data/catalog.json (tests/catalog_test.gd checks).\n"
block += "const RESOURCE_ORDER := [\n" + gd_list(['"%s"' % k for k in order]) + "\n]\n"
block += "## Which shelf of the Exchange each good sits on.\n"
block += "const RESOURCE_KIND := {\n" + gd_list(['"%s": "%s"' % (k, "raw" if k in mats else ("food" if k in food else "crafted")) for k in order], 4) + "\n}\n"
block += "const RESOURCE_NAMES := {\n" + gd_list(['"%s": "%s"' % (k, name(k).replace('"', '\\"')) for k in order], 4) + "\n}\n"
block += "const RESOURCE_DESC := {\n" + "\n".join('\t"%s": "%s",' % (k, desc(k).replace('"', '\\"')) for k in order).rstrip(",") + "\n}\n"
block += "const BASE_PRICE := {\n" + gd_list(['"%s": %d' % (k, value(k)) for k in order], 6) + "\n}\n"

p = "scripts/company_state_base.gd"
s = open(p).read()
start = s.index("## Goods the warehouse holds and the markets trade")
end = s.index("const BASE_PRICE := {", start)
end = s.index("}\n", end) + 2
s = s[:start] + block + s[end:]
open(p, "w").write(s)
print("%d goods: %d materials, %d crafted, %d potions, %d food" % (len(order), len(mats), len(crafted), len(potions), len(food)))
