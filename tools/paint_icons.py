# Recolours of existing icons: (source, target, {old rgb: new rgb})
RECOLOR = {
    "oak": ("timber", {}),
    "steel_ingot": ("iron", {(93, 107, 136): (110, 120, 140), (137, 150, 182): (170, 180, 196), (187, 208, 225): (230, 236, 244)}),
    "silversteel_ingot": ("iron", {(93, 107, 136): (90, 120, 150), (137, 150, 182): (140, 190, 220), (187, 208, 225): (210, 240, 250)}),
    "amber": ("crystal", None),
    "garnet": ("crystal", None),
}


def paint(name, art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, [len(r) for r in rows])
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                im.putpixel((x, y), PAL[ch])
    return im


def tint(src, base_rgb, lo, hi):
    """Map every coloured pixel's brightness onto a ramp from lo to hi (outline stays black)."""
    im = Image.open(OUT + src + ".png").convert("RGBA")
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    for y in range(16):
        for x in range(16):
            r, g, b, a = im.getpixel((x, y))
            if a == 0:
                continue
            if (r, g, b) == (0, 0, 0):
                out.putpixel((x, y), (0, 0, 0, a))
                continue
            t = (r + g + b) / (3 * 255)
            out.putpixel((x, y), tuple(int(lo[i] + (hi[i] - lo[i]) * t) for i in range(3)) + (a,))
    return out


def empty_from(im):
    """A faint outline of a shape, like empty_helmet.png."""
    ref = Image.open(OUT + "empty_helmet.png").convert("RGBA")
    colour = next(p for p in ref.getdata() if p[3] > 0)
    out = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(16):
        for x in range(16):
            if im.getpixel((x, y)) == K:
                out.putpixel((x, y), colour)
    return out


