    made = {}
    for name, art in ICONS.items():
        made[name] = paint(name, art)
        made[name].save(OUT + "item_%s.png" % name)
    for name, (src, mapping) in RECOLOR.items():
        if name == "oak":
            im = tint(src, None, (70, 40, 24), (176, 120, 70))
        elif name == "amber":
            im = tint(src, None, (150, 80, 10), (255, 210, 110))
        elif name == "garnet":
            im = tint(src, None, (90, 10, 24), (240, 110, 120))
        else:
            im = Image.open(OUT + src + ".png").convert("RGBA")
            for y in range(16):
                for x in range(16):
                    r, g, b, a = im.getpixel((x, y))
                    if (r, g, b) in mapping:
                        im.putpixel((x, y), mapping[(r, g, b)] + (a,))
        im.save(OUT + "%s.png" % name)
    # Goods drawn from shapes.
    made["lump"].save(OUT + "coal.png")
    made["pelt"].save(OUT + "wolf_pelt.png")
    made["skein"].save(OUT + "spider_silk.png")
    made["bottle"].save(OUT + "healing_draught.png")
    # Empty slots.
    for slot, shape in [("main_hand", "dagger"), ("off_hand", "shield"), ("trinket", "ring"), ("back", "pack"), ("food", "bowl"), ("potion", "bottle")]:
        empty_from(made[shape]).save(OUT + "empty_%s.png" % slot)
