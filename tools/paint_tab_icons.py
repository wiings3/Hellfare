"""Paints the 24x24 bookmark icon for the Workshop chapter (run from the project root),
in the style of the other icons in assets/ui/tab_icons: dark outline, steel and wood tones."""
from PIL import Image

PAL = {"k": (40, 28, 32), "x": (72, 88, 106), "y": (112, 132, 152), "z": (176, 192, 206),
       "a": (141, 102, 50), "g": (184, 138, 71), "h": (208, 166, 103), "r": (154, 74, 88)}

